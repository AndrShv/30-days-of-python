def simple_generator():
    print("--- Начали работу ---")
    yield "Первая порция данных"

    print("--- Продолжаем работу ---")
    yield "Вторая порция данных"

    print("--- Конец ---")


# Просто вызов функции не запустит код внутри нее!
gen = simple_generator()

# Чтобы получить данные, мы гоняем генератор через цикл for
for data in gen:
    print("Получено из генератора:", data)